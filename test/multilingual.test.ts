import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { beforeAll, describe, expect, it } from 'vitest';

import { explainCommandFor, isWatched, WATCHED_EDITOR_IDS } from '../src/core/language.js';
import { discoverPacks } from '../src/core/pack/discover.js';
import { indexBySignature } from '../src/core/pack/schema.js';
import type { ChapterPack, ConceptEntry } from '../src/core/pack/types.js';
import { codeCandidates, normalizeMessage, SignatureResolver, toSignature } from '../src/core/signature.js';
import { signatureKey } from '../src/core/types.js';

const PACKS_DIR = fileURLToPath(new URL('../packs', import.meta.url));
const CAPTURE = fileURLToPath(new URL('./fixtures/python/diagnostics.json', import.meta.url));

/**
 * What a real analyzer said about the fixture corpus.
 *
 * Regenerated by `scripts/capture-python-diagnostics.py`, never edited by hand. This file exists
 * because the first Python pack was authored from remembered *traceback* text and matched nothing:
 * VS Code diagnostics come from Pylance, Pylint and Ruff, and none of the three phrases anything
 * the way CPython does at runtime. A pack written against imagination passes every test you write
 * against the same imagination.
 */
interface Captured {
  analyzer: string;
  file: string;
  code: string;
  message: string;
}

interface Capture {
  /** Analyzer versions this was recorded with, so drift is visible rather than silent. */
  capturedWith: Record<string, string>;
  diagnostics: Captured[];
}

const capture: Capture = JSON.parse(readFileSync(CAPTURE, 'utf8')) as Capture;
const captured = capture.diagnostics;

/** Which concept each corpus file is supposed to teach. */
const FILE_CONCEPT: Record<string, string> = {
  'scope_assignment.py': 'python/scope.assignment',
  'mutable_defaults.py': 'python/functions.mutable-defaults',
  'none_propagation.py': 'python/types.none-propagation',
  'mutate_while_iterating.py': 'python/collections.mutate-while-iterating',
  'late_binding.py': 'python/scope.late-binding',
};

/**
 * Diagnostics the corpus provokes that are genuinely about something else.
 *
 * Listed individually rather than filtered by a rule prefix, so that a newly-appearing diagnostic
 * fails the suite and has to be looked at rather than silently absorbed.
 */
const NOT_OUR_CONCEPT = new Set([
  'W0603:global-statement',
  'W0621:redefined-outer-name',
  'R1721:unnecessary-comprehension',
  'PLW0603',
  'PERF401',
  'C416',
  // `object` is not callable — provoked by the corpus's `Optional[object]` annotation, and about
  // callability rather than about None.
  'reportCallIssue',
]);

let packs: ChapterPack[];
let resolver: SignatureResolver;
let index: Map<string, ConceptEntry>;

beforeAll(async () => {
  const found = await discoverPacks(PACKS_DIR);
  expect(found.failures, JSON.stringify(found.failures)).toEqual([]);
  packs = found.packs;
  resolver = new SignatureResolver(packs);

  index = new Map();
  for (const pack of packs) {
    for (const [key, concept] of indexBySignature(pack)) {
      if (!index.has(key)) index.set(key, concept);
    }
  }
});

function conceptFor(row: Captured): string | undefined {
  const sig = resolver.resolve('python', row.code, row.message);
  return index.get(signatureKey(sig))?.id;
}

describe('the captured corpus is real', () => {
  it('records the analyzers that produced it', () => {
    expect(Object.keys(capture.capturedWith).sort()).toEqual([
      'pylint',
      'pyright',
      'python',
      'ruff',
    ]);
  });

  it('has diagnostics from all three analyzers a VS Code user might have', () => {
    const analyzers = new Set(captured.map((r) => r.analyzer));
    expect([...analyzers].sort()).toEqual(['pylint', 'pyright', 'ruff']);
  });

  it('covers every corpus file', () => {
    const files = new Set(captured.map((r) => r.file));
    expect([...files].sort()).toEqual(Object.keys(FILE_CONCEPT).sort());
  });
});

describe('every real diagnostic reaches the right concept', () => {
  const relevant = captured.filter((r) => !NOT_OUR_CONCEPT.has(r.code));

  it.each(relevant)(
    '$analyzer $code -> $file',
    (row) => {
      expect(conceptFor(row), `unclaimed: [${row.analyzer} ${row.code}] ${row.message}`).toBe(
        FILE_CONCEPT[row.file]
      );
    }
  );

  it('leaves the genuinely-unrelated diagnostics alone', () => {
    // Claiming these would mean teaching about closures because a comprehension was suboptimal.
    for (const row of captured.filter((r) => NOT_OUR_CONCEPT.has(r.code))) {
      expect(conceptFor(row), `wrongly claimed: [${row.code}] ${row.message}`).toBeUndefined();
    }
  });

  it('reaches every concept the pack declares, from at least one real diagnostic', () => {
    const reached = new Set(captured.map(conceptFor).filter(Boolean));
    const declared = packs
      .filter((p) => p.meta.language === 'python')
      .flatMap((p) => p.concepts.map((c) => c.id));
    const unreachable = declared.filter((id) => !reached.has(id));
    expect(unreachable, `concepts no real diagnostic reaches: ${unreachable.join(', ')}`).toEqual(
      []
    );
  });
});

describe('the code forms each analyzer actually sends', () => {
  it('splits the composite that vscode-pylint builds', () => {
    // `code=f"{msg_id}:{data.get('symbol')}"` in microsoft/vscode-pylint's lsp_server.py.
    expect(codeCandidates('E0601:used-before-assignment')).toEqual([
      'E0601:used-before-assignment',
      'E0601',
      'used-before-assignment',
    ]);
  });

  it('leaves a single-token code alone', () => {
    expect(codeCandidates('F823')).toEqual(['F823']);
    expect(codeCandidates('reportUnboundVariable')).toEqual(['reportUnboundVariable']);
  });

  it('ignores an empty code', () => {
    expect(codeCandidates('   ')).toEqual([]);
  });

  it('reaches one concept from all three analyzers naming the same mistake', () => {
    // The point of carrying codes *and* patterns: pylint, ruff and Pylance describe
    // used-before-assignment in three unrelated ways, and all three must land in one place.
    const ids = [
      resolver.resolve('python', 'E0601:used-before-assignment', "Using variable 'TOTAL' before assignment"),
      resolver.resolve('python', 'F823', 'Local variable `TOTAL` referenced before assignment'),
      resolver.resolve('python', 'reportUnboundVariable', '"TOTAL" is unbound'),
    ].map((s) => index.get(signatureKey(s))?.id);
    expect(ids).toEqual([
      'python/scope.assignment',
      'python/scope.assignment',
      'python/scope.assignment',
    ]);
  });

  it('recovers a concept from the message when the rule code is too generic to claim', () => {
    // reportAttributeAccessIssue fires for typos as well as for None, so the pack cannot claim the
    // code — only the half of the message that is specifically about None.
    const sig = resolver.resolve(
      'python',
      'reportAttributeAccessIssue',
      'Cannot access attribute "strip" for class "None"'
    );
    expect(sig.kind).toBe('pattern');
    expect(index.get(signatureKey(sig))?.id).toBe('python/types.none-propagation');

    const typo = resolver.resolve(
      'python',
      'reportAttributeAccessIssue',
      'Cannot access attribute "strp" for class "str"'
    );
    expect(index.get(signatureKey(typo))).toBeUndefined();
  });
});

describe('the resolver keeps the rest of the system working', () => {
  it('was unreachable through the naive path, which is why the resolver exists', () => {
    // A pack declares a regex; the detector produced a normalized message; the concept index is an
    // exact map. The two could never meet, so every codeless language silently taught nothing.
    const naive = toSignature('python', undefined, 'Cannot access attribute "strip" for class "None"');
    expect(index.has(signatureKey(naive))).toBe(false);
  });

  it('gives the same signature for the same mistake on different variables', () => {
    const a = resolver.resolve('python', 'F823', 'Local variable `total` referenced before assignment');
    const b = resolver.resolve('python', 'F823', 'Local variable `seen` referenced before assignment');
    expect(signatureKey(a)).toBe(signatureKey(b));
  });

  it('falls back to a normalized message for an error no pack claims', () => {
    const message = 'Import "requests" could not be resolved';
    const sig = resolver.resolve('python', undefined, message);
    expect(sig).toEqual({ kind: 'pattern', language: 'python', value: normalizeMessage(message) });
    // Unteachable, but still a stable key — the detector's timing heuristics keep working.
    expect(index.has(signatureKey(sig))).toBe(false);
  });

  it('keeps an unknown code as a code, so cooldowns still group it', () => {
    expect(resolver.resolve('python', 'reportGeneralTypeIssues', 'whatever')).toEqual({
      kind: 'code',
      language: 'python',
      value: 'reportGeneralTypeIssues',
    });
  });

  it('does not let one language claim messages belonging to another', () => {
    const sig = resolver.resolve('rust', undefined, 'Cannot access attribute "strip" for class "None"');
    expect(index.has(signatureKey(sig))).toBe(false);
  });

  it('leaves a language with real codes alone', () => {
    expect(resolver.resolve('rust', 'E0502', 'cannot borrow as mutable')).toEqual({
      kind: 'code',
      language: 'rust',
      value: 'E0502',
    });
  });

  it('survives a malformed pattern rather than refusing to load the packs', () => {
    const bad = [
      {
        meta: { language: 'python' },
        concepts: [
          { signatures: [{ kind: 'pattern', language: 'python', value: '([unclosed' }] },
          { signatures: [{ kind: 'pattern', language: 'python', value: 'still fine' }] },
        ],
      },
    ] as unknown as ChapterPack[];

    const reported: string[] = [];
    const r = new SignatureResolver(bad, (pattern) => reported.push(pattern));
    expect(reported).toEqual(['([unclosed']);
    expect(r.size).toBe(1);
    expect(r.resolve('python', undefined, 'still fine here').value).toBe('still fine');
  });
});

describe('no pattern is decoration', () => {
  // A pattern that compiles but nothing reaches is the exact failure this file was written to
  // catch, and it is invisible at runtime: the tutor simply stays quiet.
  it('has a real diagnostic exercising every python pattern', () => {
    const declared = packs
      .filter((p) => p.meta.language === 'python')
      .flatMap((p) => p.concepts)
      .flatMap((c) => c.signatures)
      .filter((s) => s.kind === 'pattern')
      .map((s) => s.value);

    // Codes win over patterns at resolve time, so a pattern is exercised by matching the message
    // directly rather than by going through the full resolver.
    const messages = captured.map((r) => r.message);
    const never = declared.filter((p) => !messages.some((m) => new RegExp(p, 'i').test(m)));
    expect(never, `patterns no captured diagnostic reaches: ${never.join(' | ')}`).toEqual([]);
  });

  it('has a real diagnostic exercising every python code', () => {
    const declared = packs
      .filter((p) => p.meta.language === 'python')
      .flatMap((p) => p.concepts)
      .flatMap((c) => c.signatures)
      .filter((s) => s.kind === 'code')
      .map((s) => s.value);

    const seen = new Set(captured.flatMap((r) => codeCandidates(r.code)));
    const never = declared.filter((c) => !seen.has(c));
    // Pylance's Optional rules need code the corpus does not contain (a context manager, an
    // arithmetic operand). They are listed so the gap is deliberate rather than discovered later.
    expect(never.sort()).toEqual(['reportOptionalContextManager', 'reportOptionalOperand'].sort());
  });
});

describe('no pack may declare patterns without evidence', () => {
  /**
   * The rule that would have caught the original mistake on day one.
   *
   * A code is checkable by inspection — `E0502` either is or is not what rustc emits. A message
   * pattern is not: it is a claim about the exact wording some analyzer produces, and the only way
   * to know is to run that analyzer. So a pack that declares patterns must ship the captured output
   * they were derived from, and the suite must actually read it.
   */
  it('ships a captured diagnostics fixture for every language that uses patterns', () => {
    const withPatterns = new Set(
      packs
        .filter((p) => p.concepts.some((c) => c.signatures.some((s) => s.kind === 'pattern')))
        .map((p) => p.meta.language)
    );

    for (const language of withPatterns) {
      const path = fileURLToPath(
        new URL(`./fixtures/${language}/diagnostics.json`, import.meta.url)
      );
      expect(
        existsSync(path),
        `${language} declares message patterns but ships no captured analyzer output at ${path} — see scripts/capture-python-diagnostics.py`
      ).toBe(true);
      const file = JSON.parse(readFileSync(path, 'utf8')) as Capture;
      expect(file.diagnostics.length, `${language}'s capture is empty`).toBeGreaterThan(0);
      expect(
        Object.keys(file.capturedWith).length,
        `${language}'s capture does not record which analyzer versions produced it`
      ).toBeGreaterThan(0);
    }
  });
});

describe('the language table', () => {
  it('watches every language a pack teaches', () => {
    for (const pack of packs) {
      expect(isWatched(pack.meta.language), `${pack.meta.id} is unreachable`).toBe(true);
    }
  });

  it('offers the compiler explanation only where one exists', () => {
    expect(explainCommandFor({ kind: 'code', language: 'rust', value: 'E0502' })).toBe(
      'rustc --explain E0502'
    );
    // Python has no `rustc --explain`, and inventing one would be worse than staying quiet.
    expect(
      explainCommandFor({ kind: 'code', language: 'python', value: 'E0601' })
    ).toBeUndefined();
    expect(
      explainCommandFor({ kind: 'code', language: 'rust', value: 'clippy::needless_range_loop' })
    ).toBeUndefined();
  });

  it('names every watched editor id', () => {
    expect(WATCHED_EDITOR_IDS).toContain('rust');
    expect(WATCHED_EDITOR_IDS).toContain('python');
  });
});
